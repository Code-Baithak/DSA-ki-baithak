package Baithak_16;

public class Typecasting {
    static void main() {
        // Implicit Typecasting
        int a = 10;
        double b = a;
        System.out.println(b);

        byte val1 = 13;


        // Explicit Typecasting
        double c = 10.7;
        int d = (int) c;
        System.out.println(d);

        byte val2 = (byte) 130;
        System.out.println(val2);
    }
}
